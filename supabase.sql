-- ============================================================================
-- SHIFT RUNNER · 云端排行榜建表脚本（账号版）
--
-- 用法：打开 Supabase 控制台 → 左侧 SQL Editor → New query →
--       把本文件全部内容粘贴进去 → Run。可以重复执行。
--
-- 前置设置（只做一次）：
--   Authentication → Sign In / Providers → Email →
--   关闭 "Confirm email"（邮箱确认），否则注册后无法立即登录。
--
-- 安全模型：
--   * 只有已登录用户可以写入，且只能写自己的记录（RLS 校验 user_id）
--   * 任何人（含未登录）都可以读取榜单
--   * 不开放 UPDATE / DELETE，别人既改不了也删不掉别人的成绩
--   * 字段加了长度/范围约束，同一账号 3 秒内只能提交一次
-- ============================================================================

-- 1. 成绩表 --------------------------------------------------------------
create table if not exists public.scores (
  id          bigint generated by default as identity primary key,
  user_id     uuid        references auth.users(id) on delete cascade,
  name        text        not null check (char_length(name) between 1 and 12),
  dist        integer     not null check (dist between 0 and 100000),
  pts         integer     not null default 0 check (pts between 0 and 1000000),
  combo       integer     not null default 0 check (combo between 0 and 10000),
  created_at  timestamptz not null default now()
);

-- 旧版表补上 user_id 列（第一次建表时已经包含，这里兼容升级）
alter table public.scores
  add column if not exists user_id uuid references auth.users(id) on delete cascade;

-- 排名查询用的索引（距离优先，同距离看得分）+ 按账号查询的索引
create index if not exists scores_rank_idx
  on public.scores (dist desc, pts desc);
create index if not exists scores_user_idx
  on public.scores (user_id);

-- 2. 表级授权 ------------------------------------------------------------
-- Supabase 新版项目默认不给 anon / authenticated 任何表权限，光有 RLS 策略不够。
-- 缺少这些语句时，前端会收到 401：permission denied for table scores。
grant usage on schema public to anon, authenticated;
grant select on public.scores to anon, authenticated;   -- 榜单公开可读
grant insert on public.scores to authenticated;         -- 只有登录用户能写

-- 3. 开启行级安全 --------------------------------------------------------
alter table public.scores enable row level security;

-- 提交成绩：必须是本人（user_id 等于当前登录账号）
drop policy if exists "scores_insert" on public.scores;
create policy "scores_insert" on public.scores
  for insert
  to authenticated
  with check (auth.uid() = user_id);

-- 读取榜单：所有人都可以看
drop policy if exists "scores_select" on public.scores;
create policy "scores_select" on public.scores
  for select
  to anon, authenticated
  using (true);

-- 注意：这里没有 update / delete 策略，
-- 因此任何人（包括登录用户）都无法改动或删除已有成绩。

-- 4. 基础防刷：同一账号 3 秒内只能提交一次 -------------------------------
create or replace function public.scores_rate_limit()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if exists (
    select 1
    from public.scores
    where user_id = new.user_id
      and created_at > now() - interval '3 seconds'
  ) then
    raise exception '提交过于频繁，请稍后再试';
  end if;
  return new;
end;
$$;

drop trigger if exists scores_rate_limit_trg on public.scores;
create trigger scores_rate_limit_trg
  before insert on public.scores
  for each row
  execute function public.scores_rate_limit();

-- 5. 可选升级：真实跑动距离（与得分 dist 分离） -------------------------
-- 说明：
--   * dist 字段继续表示「得分」，保持历史成绩与旧前端兼容；
--   * distance 表示本局真实跑动距离，旧记录为 NULL，前端显示「—」，不会伪造；
--   * 前端检测到该列不存在时会自动降级为旧查询，不影响使用。
alter table public.scores
  add column if not exists distance integer;

-- 距离范围约束（允许 NULL；仅对新写入生效）
do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'scores_distance_range'
  ) then
    alter table public.scores
      add constraint scores_distance_range
      check (distance is null or distance between 0 and 100000);
  end if;
end $$;
