-- ============================================================================
-- SHIFT RUNNER · 云端排行榜建表脚本
--
-- 用法：打开 Supabase 控制台 → 左侧 SQL Editor → New query →
--       把本文件全部内容粘贴进去 → Run。
--
-- 安全模型：
--   * 只开放 INSERT（提交成绩）与 SELECT（读取榜单）
--   * 不开放 UPDATE / DELETE，所以匿名 key 泄露也无法篡改别人的记录
--   * 字段加了长度/范围约束，避免塞入超长昵称或异常数值
--   * 同一昵称 3 秒内只能提交一次，挡住最粗暴的连点刷分
-- ============================================================================

-- 1. 成绩表 --------------------------------------------------------------
create table if not exists public.scores (
  id          bigint generated by default as identity primary key,
  name        text        not null check (char_length(name) between 1 and 12),
  dist        integer     not null check (dist between 0 and 100000),
  pts         integer     not null default 0 check (pts between 0 and 1000000),
  combo       integer     not null default 0 check (combo between 0 and 10000),
  created_at  timestamptz not null default now()
);

-- 排名查询用的索引（距离优先，同距离看得分）
create index if not exists scores_rank_idx
  on public.scores (dist desc, pts desc);

-- 2. 表级授权 ------------------------------------------------------------
-- Supabase 新版项目默认不给 anon 角色任何表权限，光有 RLS 策略是不够的：
-- 缺这两行时，前端请求会被直接拒绝（401 / permission denied for table scores）。
grant usage on schema public to anon, authenticated;
grant select, insert on public.scores to anon, authenticated;

-- 3. 开启行级安全 --------------------------------------------------------
alter table public.scores enable row level security;

-- 允许任何人插入成绩（前端提交）
drop policy if exists "scores_insert" on public.scores;
create policy "scores_insert" on public.scores
  for insert
  to anon, authenticated
  with check (true);

-- 允许任何人读取榜单
drop policy if exists "scores_select" on public.scores;
create policy "scores_select" on public.scores
  for select
  to anon, authenticated
  using (true);

-- 注意：这里没有 update / delete 策略，
-- 因此即使有人拿到 anon key，也只能新增与读取，无法改动已有记录。

-- 4. 基础防刷：同一昵称 3 秒内只能提交一次 -------------------------------
create or replace function public.scores_rate_limit()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if exists (
    select 1
    from public.scores
    where name = new.name
      and created_at > now() - interval '3 seconds'
  ) then
    raise exception '提交过于频繁，请稍后再试';
  end if;
  return new;
end;
$$;

drop trigger if exists scores_rate_limit_trg on public.scores;
create trigger scores_rate_limit_trg
  before insert on public.scores
  for each row
  execute function public.scores_rate_limit();
